test("Excel preview prevents invalid and duplicate rows from being silently committed", async ({page}) => {
  await login(page);
  const existing=seedRecords()[0];
  const newRecord={...existing,clientName:"QA Excel Client",channelName:"QA Excel Channel"};
  const badRecord={...existing,clientName:"QA Invalid Client",payoutDate:"not-a-date"};
  const payload=createWorkbook([newRecord,existing,badRecord]);
  await page.goto("/ib-records/add");
  await page.getByRole("tab",{name:"Import Excel"}).click();
  await page.getByLabel("Upload Excel file",{exact:true}).setInputFiles({name:"qa-records.xlsx",mimeType:"application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",buffer:payload});
  await expect(page.getByText("3 rows detected",{exact:true})).toBeVisible();
  await expect(page.getByText("1 Possible duplicates",{exact:true})).toBeVisible();
  await expect(page.getByText("1 Invalid",{exact:true})).toBeVisible();
  const before=await (await page.request.get("/api/ib-records")).json();
  expect(before.records.some(r=>r.clientName==="QA Excel Client")).toBe(false);
  await page.getByRole("button",{name:"Import 1 valid records",exact:true}).click();
  await expect(page.getByText("Import complete",{exact:true})).toBeVisible();
  await expect(page.getByText("1 added · 0 updated · 2 skipped",{exact:true})).toBeVisible();
  const after=await (await page.request.get("/api/ib-records")).json();
  expect(after.records.some(r=>r.clientName==="QA Excel Client")).toBe(true);
  expect(after.records.some(r=>r.clientName==="QA Invalid Client")).toBe(false);
  // The server repeats validation even if a client tries to bypass the preview.
  const response=await page.request.post("/api/import",{data:{inputs:[{...newRecord,totalSalary:7000},badRecord],duplicateMode:"update"}});
  expect(await response.json()).toEqual({added:0,updated:1,skipped:1});
  const updated=await (await page.request.get("/api/ib-records")).json();
  expect(updated.records.find(r=>r.clientName==="QA Excel Client").totalSalary).toBe(7000);
});
