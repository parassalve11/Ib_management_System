test("logout revokes browser access and forged sessions are rejected", async ({page,context}) => {
  await login(page);
  await page.getByRole("button",{name:/Accountant/}).click();
  await page.getByRole("button",{name:"Sign out",exact:true}).click();
  await expect(page).toHaveURL(/\/login$/);
  expect((await page.request.get("/api/ib-records")).status()).toBe(401);
  await context.addCookies([{name:"bytefx_session",value:"forged.signature",url:"http://127.0.0.1:3100"}]);
  expect((await page.request.get("/api/ib-records")).status()).toBe(401);
});
